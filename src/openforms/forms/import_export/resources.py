class CombinedResourceMeta(type(ModelResource), ABCMeta):
    pass


class BaseResource(ABC, ModelResource, metaclass=CombinedResourceMeta):
    """
    The base resource for all import/export resources.

    Attributes:
        deep_comparison_fields:
            The fields to use for deep comparison when searching for an existing
            instance. An instance will have to match all these fields to be considered
            an exact match.
        identifier_field:
            The field that uniquely identifies the instance. This field will be assigned
            a new identifier value when the identifier in the import-data is already in
            use, and we want to create a new instance. The new identifier will be
            generated by `generate_identifier()`.
    """

    deep_comparison_fields: Sequence[str] = ()
    identifier_field: str

    @abstractmethod
    def export_for_form(self, form: Form) -> Dataset:
        raise NotImplementedError(
            f"{self.__class__.__name__} must implement export_for_form()"
        )

    @abstractmethod
    def generate_identifier(self, row: dict[str, Any]) -> str | UUID:
        """
        A method to generate a unique identifier used when creating a new instance.

        The identifier will be assigned to the `identifier_field` of the instance.
        """
        raise NotImplementedError(
            f"{self.__class__.__name__} must implement generate_identifier()"
        )

    @override
    def get_or_init_instance(
        self, instance_loader: BaseInstanceLoader, row: dict[str, Any]
    ) -> tuple[JSONObject, bool]:
        """
        Search for an existing instance with matching attributes.

        The default get_or_init_instance uses the import_id_fields. This does a lookup
        using the resource unique identifier.

        If the identifier lookup doesn't find an existing instance, we do a deep
        comparison and return the first match.

        Finally, if no match is found, we create a new instance.

        The return value is a tuple of (instance, is_new).
        """
        # Search for the instance using the import_id_fields. Typically, this will return
        # the instance with the same PK.
        instance: JSONObject | None = super().get_instance(instance_loader, row)
        if instance is not None:
            row["_matched_existing_instance"] = True
            return instance, False

        # Collect the parameters for the deep comparison.
        params: JSONObject = {}
        for key in self.deep_comparison_fields:
            params[key] = self.fields[key].clean(row)

        # Perform the deep comparison and return the first match.
        if params and (found_instance := self.get_queryset().filter(**params).first()):
            row["_matched_existing_instance"] = True
            return found_instance, False

        # No match found, create and return a new instance.
        new_instance: JSONObject = super().init_instance(row)
        row["_generated_new_identifier"] = True
        return new_instance, True

    @override
    def import_field(
        self,
        field: Field,
        instance: JSONObject,
        row: dict[str, Any],
        is_m2m=False,
        **kwargs,
    ) -> None:
        if (
            field.attribute
            and field.attribute == self.identifier_field
            and getattr(row, "_generated_new_identifier", False)
        ):
            # Set the identifier field to a new value, generated by the subclass.
            setattr(instance, field.attribute, self.generate_identifier(row))
            return

        # Import the field value normally.
        super().import_field(field, instance, row, is_m2m=is_m2m, **kwargs)

    @override
    def skip_row(
        self,
        instance: JSONObject,
        original: JSONObject,
        row: dict[str, Any],
        import_validation_errors=None,
    ) -> bool:
        # Skip rows that have been matched to an existing instance.
        if row.get("_matched_existing_instance"):
            return True

        return super().skip_row(instance, original, row, import_validation_errors)


class ProductResource(BaseResource):
    deep_comparison_fields = ("name", "price", "information")
    identifier_field = "uuid"

    class Meta:
        model = Product
        import_id_fields = ("uuid",)
        fields = ("uuid", "name", "price", "information")
        store_instance = True
        store_row_values = True

    def export_for_form(self, form: Form) -> Dataset:
        products = (
            Product.objects.none()
            if not form.product_id  # pyright: ignore[reportAttributeAccessIssue]
            else Product.objects.filter(pk=form.product_id)  # pyright: ignore[reportAttributeAccessIssue]
        )
        return self.export(queryset=products)

    def generate_identifier(self, row: dict[str, Any]) -> UUID:
        return uuid4()


class WMSTileLayerResource(BaseResource):
    deep_comparison_fields = ("name", "url")
    identifier_field = "uuid"

    class Meta:
        model = MapWMSTileLayer
        import_id_fields = ("uuid",)
        fields = ("uuid", "name", "url")
        store_instance = True
        store_row_values = True

    def export_for_form(self, form: Form) -> Dataset:
        tile_layer_uuids: set[str] = set()
        for step in form.form_step_map.values():
            for component in step.form_definition.iter_components():
                if component["type"] == "map":
                    tile_layer_uuids.update(
                        overlay["uuid"]
                        for overlay in component.get("overlays", [])
                        if overlay["uuid"] != ""
                    )

        return self.export(
            queryset=MapWMSTileLayer.objects.filter(uuid__in=tile_layer_uuids)
        )

    def generate_identifier(self, row: dict[str, Any]) -> UUID:
        return uuid4()


class WMTSTileLayerResource(BaseResource):
    deep_comparison_fields = ("label", "url")
    identifier_field = "identifier"

    class Meta:
        model = MapTileLayer
        import_id_fields = ("identifier",)
        fields = ("identifier", "label", "url")
        store_instance = True
        store_row_values = True

    def export_for_form(self, form: Form) -> Dataset:
        wmts_tile_layer_identifiers: set[str] = set()
        for step in form.form_step_map.values():
            for component in step.form_definition.iter_components():
                if component["type"] == "map" and component.get("tileLayerIdentifier"):
                    wmts_tile_layer_identifiers.add(component["tileLayerIdentifier"])

        return self.export(
            queryset=MapTileLayer.objects.filter(
                identifier__in=wmts_tile_layer_identifiers
            )
        )

    def generate_identifier(self, row: dict[str, Any]) -> str:
        current_identifier: str = row["identifier"]

        # In case the identifier already has a numeric suffix, use that as the starting
        # point.
        match = re.match(r"^(.*?)(\d+)?$", current_identifier)
        if match:
            identifier_base = match.group(1)
            identifier_index = int(match.group(2)) if match.group(2) is not None else 0
        else:
            identifier_base = current_identifier
            identifier_index = 0

        new_identifier = current_identifier
        existing_identifiers = MapTileLayer.objects.values_list("identifier", flat=True)

        while new_identifier in existing_identifiers:
            identifier_index += 1
            new_identifier = "".join((identifier_base, str(identifier_index)))

        return new_identifier


class YiviAttributeGroupResource(BaseResource):
    deep_comparison_fields = ("name", "description", "attributes")
    identifier_field = "uuid"

    class Meta:
        model = AttributeGroup
        import_id_fields = ("uuid",)
        fields = ("uuid", "name", "description", "attributes")
        store_instance = True
        store_row_values = True

    def export_for_form(self, form: Form) -> Dataset:
        yivi_attribute_group_uuids = set(
            chain.from_iterable(
                yivi_backend.options.get("additional_attributes_groups", [])
                for yivi_backend in form.auth_backends.filter(backend=YIVI_PLUGIN_ID)
            )
        )

        return self.export(
            queryset=AttributeGroup.objects.filter(uuid__in=yivi_attribute_group_uuids)
        )

    def generate_identifier(self, row: dict[str, Any]) -> UUID:
        return uuid4()
